// Build step: embed the Python reference implementation, plus the evidence checks, as the
// verify.py that every evidence package carries. One source of truth: the same file the
// conformance suite tests (conformance/impl.py).
// SPDX-License-Identifier: Apache-2.0
import { readFileSync, writeFileSync } from 'node:fs';
const impl = readFileSync(new URL('../conformance/impl.py', import.meta.url), 'utf8');
const guard = /\nif __name__ == "__main__":\n    main\(\)\n?$/;
if (!guard.test(impl)) throw new Error('conformance/impl.py no longer ends with its main guard; update this script');
const evidence = readFileSync(new URL('../conformance/evidence_main.py', import.meta.url), 'utf8');
const py = impl.replace(guard, '\n') + evidence;
writeFileSync(
  new URL('../src/evidence-verifier.generated.ts', import.meta.url),
  '// GENERATED by scripts/embed-verifier.mjs from conformance/impl.py and conformance/evidence_main.py. Do not edit.\n' +
    '// SPDX-License-Identifier: Apache-2.0\n' +
    `export const VERIFY_PY = ${JSON.stringify(py)};\n`,
);
